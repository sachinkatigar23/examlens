import { Answer } from '../models/Answer.js';
import { Job } from '../models/Job.js';
import { Question } from '../models/Question.js';
import { AppError } from '../utils/AppError.js';
import { collectAiStream } from './aiService.js';
import { withFileNames } from './streamRelay.js';

// "Answer all": answers every question-bank question that has no cached answer, ONE AT A TIME (the GPU has
// 4 GB; parallel generations would only queue inside Ollama). Progress is stored on the Job so the UI can
// poll it, and a restarted server resumes running jobs (answered questions are skipped, so nothing is redone).

// Errors that will fail every following question too: stop the job instead of skipping question by question.
const FATAL = new Set(['ai_down', 'local_offline', 'embeddings_offline', 'model_missing', 'cloud_unavailable', 'rate_limited', 'cloud_error']);

const aborts = new Map(); // jobId -> AbortController of the answer being generated
let queue = Promise.resolve(); // jobs of different notebooks also run one after another

export function bankScope(spaceId, unit) {
  return { space: spaceId, kind: 'important', ...(unit ? { unit } : {}) };
}

// Saves (or replaces) the cached answer of a question.
export async function saveAnswer(question, { text, meta, citations }) {
  return Answer.findOneAndUpdate(
    { question: question._id },
    {
      space: question.space,
      question: question._id,
      marks: meta.marks,
      provider: meta.provider,
      model: meta.model,
      content: text,
      citations,
      grounded: meta.grounded !== false,
    },
    { upsert: true, returnDocument: 'after', setDefaultsOnInsert: true },
  );
}

async function pendingQuestions(job) {
  const questions = await Question.find(bankScope(job.space, job.unit)).select('text marks space').lean();
  const answered = new Set((await Answer.distinct('question', { question: { $in: questions.map((q) => q._id) } })).map(String));
  return { total: questions.length, pending: questions.filter((q) => !answered.has(String(q._id))) };
}

async function runJob(jobId) {
  let job = await Job.findById(jobId);
  if (!job || job.status !== 'running') return;
  const { total, pending } = await pendingQuestions(job);
  job.set({ total, done: total - pending.length });
  await job.save();

  for (const question of pending) {
    job = await Job.findById(jobId);
    if (!job || job.status !== 'running') return; // cancelled (or the notebook was deleted)
    await Job.updateOne({ _id: jobId }, { current: question.text.slice(0, 200) });

    const abort = new AbortController();
    aborts.set(String(jobId), abort);
    let result;
    try {
      result = await collectAiStream(
        '/ask',
        { space_id: String(job.space), question: question.text, marks: question.marks ?? undefined, mode: job.mode, purpose: 'exam' },
        abort.signal,
      );
    } catch (err) {
      if (abort.signal.aborted) return;
      result = { error: { message: err.message, code: 'ai_down' } };
    } finally {
      aborts.delete(String(jobId));
    }

    if (result.error) {
      if (FATAL.has(result.error.code)) {
        await Job.updateOne({ _id: jobId }, { status: 'failed', error: result.error.message, errorCode: result.error.code, current: null });
        return;
      }
      console.warn(`answer-all: skipped question ${question._id}: ${result.error.message}`);
      continue;
    }
    const citations = await withFileNames(result.meta.citations);
    // Don't overwrite an answer the student generated by hand while the job was running.
    if (!(await Answer.exists({ question: question._id }))) {
      await saveAnswer(question, { text: result.text, meta: result.meta, citations });
    }
    await Job.updateOne({ _id: jobId, status: 'running' }, { $inc: { done: 1 } });
  }
  await Job.updateOne({ _id: jobId, status: 'running' }, { status: 'done', current: null });
}

function enqueue(jobId) {
  queue = queue.then(() => runJob(jobId)).catch((err) => {
    console.error('answer-all job crashed', err);
    return Job.updateOne({ _id: jobId }, { status: 'failed', error: 'The job stopped unexpectedly. Start it again to continue.' });
  });
}

export async function startAnswerAll(space, user, { mode, unit }) {
  if (await Job.exists({ space: space._id, type: 'answer-all', status: 'running' })) {
    throw new AppError(409, 'JOB_RUNNING', 'Answer all is already running for this notebook');
  }
  const { total, pending } = await pendingQuestions({ space: space._id, unit });
  if (!total) throw new AppError(400, 'NO_QUESTIONS', 'There are no question-bank questions to answer yet');
  // Progress starts at what is already answered, so the UI never shows "1 of 22" while resuming.
  const job = await Job.create({ space: space._id, user, type: 'answer-all', mode, unit, total, done: total - pending.length });
  enqueue(job._id);
  return job;
}

export async function cancelJob(spaceId) {
  const job = await Job.findOneAndUpdate(
    { space: spaceId, type: 'answer-all', status: 'running' },
    { status: 'cancelled', current: null },
    { returnDocument: 'after' },
  );
  if (job) aborts.get(String(job._id))?.abort();
  return job;
}

export const latestJob = (spaceId) => Job.findOne({ space: spaceId, type: 'answer-all' }).sort({ createdAt: -1 }).lean();

// On server start: continue jobs that were running when the server stopped.
export async function resumeJobs() {
  const jobs = await Job.find({ status: 'running' }).sort({ createdAt: 1 }).select('_id').lean();
  for (const job of jobs) enqueue(job._id);
  if (jobs.length) console.log(`Resuming ${jobs.length} answer-all job(s)`);
}
